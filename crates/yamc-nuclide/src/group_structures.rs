/// Get a group structure by name
///
/// # Arguments
/// * `name` - Name of the group structure (case-sensitive)
///
/// # Returns
/// * `Ok(&[f64])` - Slice containing energy boundaries in eV
/// * `Err(String)` - Error message if structure name is not recognized
///
/// # Example
/// ```
/// use yamc_nuclide::group_structures::get_group_structure;
///
/// let structure = get_group_structure("VITAMIN-J-175").unwrap();
/// assert_eq!(structure.len(), 176);
/// ```
pub fn get_group_structure(name: &str) -> Result<&'static [f64], String> {
    match name {
        "XMAS-172" => Ok(&XMAS_172),
        "VITAMIN-J-175" => Ok(&VITAMIN_J_175),
        "SCALE-252" => Ok(&SCALE_252),
        "TRIPOLI-315" => Ok(&TRIPOLI_315),
        "SHEM-361" => Ok(&SHEM_361),
        "LLNL-616" => Ok(&LLNL_616),
        "CCFE-709" => Ok(&CCFE_709),
        "SCALE-999" => Ok(&SCALE_999),
        "UKAEA-1102" => Ok(&UKAEA_1102),
        "ECCO-1968" => Ok(&ECCO_1968),
        "CCFE-24-PHOTON" => Ok(&CCFE_24_PHOTON),
        "VITAMIN-J-42" => Ok(&VITAMIN_J_42),
        _ => {
            let available = available_group_structures().join(", ");
            Err(format!(
                "Unknown group structure: '{name}'. Available structures: {available}"
            ))
        }
    }
}

