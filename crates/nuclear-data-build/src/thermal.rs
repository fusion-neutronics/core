//! Thermal scattering tables: which nuclides each evaluation of a library's
//! thermal scattering sublibrary binds to.
//!
//! A thermal scattering law is named for its material, not for a nuclide:
//! its header's ZA is a material code (134 is CH4), and MF=7 MT=451, the
//! section that lists its atoms, is absent from many evaluations (H in H2O,
//! D2O, FLiBe, ZrH and CH2 among them in ENDF/B-VIII.1). So the binding is
//! stated here, per evaluation file, and checked against MF=7 MT=451
//! wherever the evaluation has it.
//!
//! Each [`Binding`] names the table (`c_H_in_H2O`, the one name for that
//! material in every library), the neutron evaluation THERMR reads for its
//! principal atom, the nuclides the table applies to (an element symbol
//! meaning every isotope of it the library's neutron sublibrary has), the
//! table name ACER records, and ACER's `nmix`, the number of atom types the
//! table's cross section is shared between. `nmix` is not cosmetic: ACER
//! divides the cross sections by it, so it goes with the bound nuclides it
//! was chosen for.
//!
//! The principal atom's neutron evaluation is the isotope whose mass is the
//! law's A0 when one is (a table per isotope), and otherwise the most abundant
//! isotope of that element (a natural-element table, such as Zr in ZrH, whose
//! A0 is the natural mass). THERMR reads its mass, so the choice moves the
//! inelastic cross section by up to a few parts in 10^4.

use std::collections::BTreeSet;

/// What one thermal scattering evaluation file becomes.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Binding {
    /// The file's stem as the library ships it, without the `_<T>K`
    /// temperature suffix of a library that publishes one file per
    /// temperature (see [`table_stem`]).
    pub file: &'static str,
    /// The table's name, which is also its folder: `c_H_in_H2O`.
    pub name: &'static str,
    /// The neutron evaluation of the principal atom, by nuclide name.
    pub principal: &'static str,
    /// The nuclides the table applies to; an element symbol is every isotope
    /// of it the library has.
    pub bound: &'static [&'static str],
    /// The table name ACER records (six characters at most).
    pub ace: &'static str,
    /// ACER's number of atom types in a mixed moderator.
    pub nmix: u32,
}

/// The stem a thermal evaluation file is bound by: its name without its
/// extension or a trailing `_<T>K` temperature (`tsl_O16_UO2_1000K.jeff` is
/// `tsl_O16_UO2`), so a library's one-file-per-temperature tables group into
/// one table.
pub fn table_stem(file_name: &str) -> String {
    let stem = file_name.rsplit_once('.').map_or(file_name, |(s, _)| s);
    if let Some((head, tail)) = stem.rsplit_once('_') {
        let digits = tail.strip_suffix('K').unwrap_or("");
        if !digits.is_empty() && digits.chars().all(|c| c.is_ascii_digit()) {
            return head.to_string();
        }
    }
    stem.to_string()
}

/// The binding for `stem` in `bindings`.
pub fn binding<'b>(bindings: &'b [Binding], stem: &str) -> Option<&'b Binding> {
    bindings.iter().find(|b| b.file == stem)
}

/// The element of a nuclide name (`"Zr"` for `"Zr90"`), or the name itself
/// when it is an element.
pub fn element(name: &str) -> &str {
    let end = name
        .find(|c: char| !c.is_ascii_alphabetic())
        .unwrap_or(name.len());
    &name[..end]
}

fn is_element(name: &str) -> bool {
    name.chars().all(|c| c.is_ascii_alphabetic())
}

/// The bound nuclides of `binding` in a library whose neutron sublibrary
/// has `neutrons`: each isotope listed, and every ground-state isotope of each
/// element listed. Refuses an isotope the library does not have, or an
/// element it has no isotope of, since a table bound to nothing would be
/// published and never apply.
pub fn bound_nuclides(
    binding: &Binding,
    neutrons: &BTreeSet<String>,
) -> Result<Vec<String>, String> {
    let mut out = Vec::new();
    for b in binding.bound {
        if is_element(b) {
            let isotopes: Vec<&String> = neutrons
                .iter()
                .filter(|n| !n.contains('_') && element(n) == *b && n.len() > b.len())
                .collect();
            if isotopes.is_empty() {
                return Err(format!(
                    "{}: binds to {b}, and the neutron sublibrary has no {b} isotope",
                    binding.name
                ));
            }
            out.extend(isotopes.into_iter().cloned());
        } else if neutrons.contains(*b) {
            out.push(b.to_string());
        } else {
            return Err(format!(
                "{}: binds to {b}, which is not in the neutron sublibrary",
                binding.name
            ));
        }
    }
    out.sort();
    out.dedup();
    Ok(out)
}

/// The ZA values ACER records for `nuclides`.
pub fn zaids(nuclides: &[String]) -> Result<Vec<i64>, String> {
    nuclides
        .iter()
        .map(|n| {
            endf::data::zam(n)
                .map(|(z, a, _)| i64::from(z) * 1000 + i64::from(a))
                .map_err(|e| format!("{n}: {e}"))
        })
        .collect()
}

